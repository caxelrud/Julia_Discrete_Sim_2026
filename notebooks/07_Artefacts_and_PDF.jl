full = print_report_pdf(bundle; root = ROOT)
    SymDict(:html => relpath(full[:html], ROOT), :pdf => relpath(full[:pdf], ROOT),
        :printed => full[:printed], :pdf_bytes => get(full, :pdf_bytes, 0))
end

